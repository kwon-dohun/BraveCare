  (solo ? SOLO[title] : undefined) ?? HELP[title] ?? (/ 신청( 알아보기|하기)$/.test(title) ? "입력한 조건에 맞을 가능성이 높은 지원이에요. '지원' 화면에서 신청 방법과 필요한 서류를 볼 수 있어요." : null);

