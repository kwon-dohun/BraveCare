export function helpRequestText(t: { title: string; when: string; memo?: string | null }, origin: string): string {
  return [
    "가족 여러분, 씩씩이에요.",
    "아직 맡은 사람이 없는 일이 있어요. 시간 되시는 분이 맡아 주실 수 있을까요?",
    "",
    `할 일: ${t.title}`,
    `일시: ${t.when}`,
    ...(t.memo ? [`메모: ${t.memo}`] : []),
    "",
    `씩씩케어를 열고 이 할 일에서 '내가 할게'를 눌러 주세요.`,
    origin,
  ].join("\n");
}
